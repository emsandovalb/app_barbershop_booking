import java.util.Properties

plugins {
    id("com.android.application")
    id("kotlin-android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing reads android/key.properties (git-ignored), which holds
// storePassword, keyPassword, keyAlias and storeFile. Without it, release
// builds fall back to the debug key: fine for local testing, but the Play
// Store rejects debug-signed bundles.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

android {
    namespace = "com.proyecto.movil.playground_booking"
    compileSdk = flutter.compileSdkVersion
    // Override NDK version to satisfy plugins (e.g., shared_preferences_android)
    ndkVersion = "27.0.12077973"

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }

    kotlinOptions {
        jvmTarget = JavaVersion.VERSION_11.toString()
    }

    defaultConfig {
        // TODO: Specify your own unique Application ID (https://developer.android.com/studio/build/application-id.html).
        applicationId = "com.proyecto.movil.playground_booking"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    // One flavor per white-label tenant so each APK gets its own launcher
    // icon (via the matching android/app/src/<flavor>/res override, as
    // generated by flutter_launcher_icons) and its own application ID —
    // without a distinct ID, installing one tenant's APK silently replaces
    // any other tenant's APK already on the same device.
    flavorDimensions += "business"
    productFlavors {
        create("barberia") {
            dimension = "business"
            applicationIdSuffix = ".barberia"
            resValue("string", "app_name", "Barbería Tres Amigos")
        }
        create("jcstudio") {
            dimension = "business"
            applicationIdSuffix = ".jcstudio"
            resValue("string", "app_name", "JC Studio")
        }
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
            }
        }
    }

    buildTypes {
        release {
            signingConfig = if (keystorePropertiesFile.exists()) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }
}

flutter {
    source = "../.."
}
